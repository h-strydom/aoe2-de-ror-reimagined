"""Generate aoe2de_ror/reimagined/ror_tech_tree.yaml: everything a Return of Rome player can build, train or
research, by name, for the reimagined campaigns' unlocks (progression.py `tech_tree`).

    uv run --with genieutils-py python scripts/gen_tech_tree.py [RoR dat folder]

Reads the game's own tech trees (CivTechTrees/*.json, every civ) and data (empires2_x2_p1.dat) from your Return of
Rome install; writes only ids and names. Buildings list every age's version (the age techs swap a building for its
next version, which a disabled base building doesn't stop), units their unit, and upgrades and research their tech.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml
from genieutils.datfile import DatFile

DAT = Path(r"C:/Program Files (x86)/Steam/steamapps/common/AoE2DE/modes/Pompeii/resources/_common/dat")
OUT = Path(__file__).resolve().parents[1] / "aoe2de_ror" / "reimagined" / "ror_tech_tree.yaml"
# Not switched: the Town Center a mission starts with (109 and its age versions) isn't built by villagers
# (they build 621, "Town Center" too), and turning it off could stop the one the player has.
KEEP = {109, 71, 141, 142}


def key(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")


def main(root: Path) -> None:
    dat = DatFile.parse(str(root / "empires2_x2_p1.dat"))
    upgrades: dict[int, set[int]] = {}                 # unit -> what techs turn it into (cmd 3)
    for t in dat.techs:
        if t.effect_id >= 0:
            for c in dat.effects[t.effect_id].effect_commands:
                if c.type == 3 and c.a >= 0 and c.b >= 0:
                    upgrades.setdefault(c.a, set()).add(c.b)

    def versions(unit: int) -> list[int]:
        seen, todo = [], [unit]
        while todo:
            u = todo.pop()
            if u not in seen:
                seen.append(u)
                todo += sorted(upgrades.get(u, ()))
        return seen

    entries: dict[str, dict[str, set[int]]] = {}
    for f in sorted((root / "CivTechTrees").glob("*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        for n in d["civ_techs_buildings"] + d["civ_techs_units"]:
            kind, nid, name = n.get("Node Type"), n.get("Node ID"), n.get("Name")
            if nid is None or not name:
                continue
            e = entries.setdefault(key(name), {"objects": set(), "techs": set()})
            if kind in ("BuildingTech", "BuildingNonTech"):
                e["objects"].update(v for v in versions(n.get("Building ID", nid)) if v not in KEEP)
            elif kind == "Unit":
                e["objects"].add(nid)
            elif kind == "UnitUpgrade":
                if (n.get("Trigger Tech ID") or -1) >= 0:
                    e["techs"].add(n["Trigger Tech ID"])
            elif kind == "Research" or n.get("Use Type") == "Tech":
                e["techs"].add(nid)
    out = {k: {kk: sorted(vv) for kk, vv in v.items() if vv} for k, v in sorted(entries.items())}
    out = {k: v for k, v in out.items() if v}
    header = __doc__.split("\n\n")[0].replace('"""', "")
    OUT.write_text("# " + header.replace("\n", "\n# ") + "\n# Generated by scripts/gen_tech_tree.py; don't edit.\n"
                   + yaml.safe_dump(out, sort_keys=False, width=120), encoding="utf-8")
    print(f"{len(out)} entries -> {OUT}")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else DAT)
